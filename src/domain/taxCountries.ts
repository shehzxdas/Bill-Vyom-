export function buildComplete195CountryTaxList(): TaxCountryConfig[] {
  const map = new Map<string, TaxCountryConfig>();

  // Add primary configured countries
  for (const c of CANONICAL_GLOBAL_TAX_COUNTRIES) {
    map.set(c.country_code, c);
  }

  // Populate remaining countries with ARCHITECTURE_READY status
  for (const entry of ALL_195_ISO_CODES) {
    if (!map.has(entry.code)) {
      map.set(entry.code, {
        country_code: entry.code,
        country_name: entry.name,
        iso_currency_code: entry.cur,
        locale: 'en',
        timezone: 'UTC',
        tax_compliance_status: 'ARCHITECTURE_READY',
        e_invoicing_required: false,
        digital_reporting_required: false,
        hierarchy_levels: ['COUNTRY'],
        default_regime_codes: ['VAT'],
        notes: `Architecture baseline ready for ${entry.name}. Awaiting specific jurisdiction rate activation.`,
      });
    }
  }

  return Array.from(map.values()).sort((a, b) => a.country_name.localeCompare(b.country_name));
}
